export const SCHEMA_VERSION = 2;

const NOW = `(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))`;

/**
 * Postgres schema (lives in the `turkce` schema — the connection's search_path).
 * Timestamps are ISO-8601 UTC strings so they compare lexicographically.
 */
export const SCHEMA_SQL = /* sql */ `
CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS cards (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tr               TEXT NOT NULL,
  en               TEXT NOT NULL,
  pos              TEXT NOT NULL,
  unit             INTEGER NOT NULL DEFAULT 0,
  "exTr"           TEXT,
  "exEn"           TEXT,
  note             TEXT,
  softens          INTEGER,
  "harmonyOverride" TEXT,
  stem             TEXT,
  aorist           TEXT,
  flags            TEXT,
  source           TEXT NOT NULL DEFAULT 'seed',
  seq              INTEGER NOT NULL DEFAULT 0,
  leech            INTEGER NOT NULL DEFAULT 0,
  created_at       TEXT NOT NULL DEFAULT ${NOW}
);
CREATE INDEX IF NOT EXISTS idx_cards_source_seq ON cards(source, seq);
CREATE INDEX IF NOT EXISTS idx_cards_tr ON cards(tr);

CREATE TABLE IF NOT EXISTS reviews (
  card_id        INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
  direction      TEXT NOT NULL,
  ease           DOUBLE PRECISION NOT NULL DEFAULT 2.5,
  interval_days  DOUBLE PRECISION NOT NULL DEFAULT 0,
  repetitions    INTEGER NOT NULL DEFAULT 0,
  due_date       TEXT NOT NULL,
  lapses         INTEGER NOT NULL DEFAULT 0,
  last_reviewed  TEXT,
  introduced_at  TEXT NOT NULL DEFAULT ${NOW},
  PRIMARY KEY (card_id, direction)
);
CREATE INDEX IF NOT EXISTS idx_reviews_due ON reviews(due_date);

CREATE TABLE IF NOT EXISTS review_log (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  card_id       INTEGER NOT NULL REFERENCES cards(id) ON DELETE CASCADE,
  direction     TEXT NOT NULL DEFAULT 'en-tr',
  timestamp     TEXT NOT NULL,
  answer_given  TEXT,
  result        TEXT NOT NULL,
  ms_taken      INTEGER,
  grade         TEXT,
  context       TEXT NOT NULL DEFAULT 'review'
);
CREATE INDEX IF NOT EXISTS idx_review_log_ts ON review_log(timestamp);
CREATE INDEX IF NOT EXISTS idx_review_log_card ON review_log(card_id, direction, id);

CREATE TABLE IF NOT EXISTS grammar_progress (
  step_id      INTEGER PRIMARY KEY,
  unlocked_at  TEXT,
  attempts     INTEGER NOT NULL DEFAULT 0,
  correct      INTEGER NOT NULL DEFAULT 0,
  mastery      DOUBLE PRECISION NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS gym_log (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  step_id       INTEGER NOT NULL,
  timestamp     TEXT NOT NULL,
  result        TEXT NOT NULL,
  answer_given  TEXT,
  expected      TEXT,
  prompt        TEXT,
  rules         TEXT,
  context       TEXT NOT NULL DEFAULT 'gym'
);
CREATE INDEX IF NOT EXISTS idx_gym_log_step ON gym_log(step_id, id);

CREATE TABLE IF NOT EXISTS lessons (
  date          TEXT PRIMARY KEY,
  kind          TEXT NOT NULL DEFAULT 'daily',
  source        TEXT NOT NULL DEFAULT 'fallback',
  json          TEXT NOT NULL,
  progress      TEXT,
  created_at    TEXT NOT NULL DEFAULT ${NOW},
  completed_at  TEXT
);

CREATE TABLE IF NOT EXISTS writings (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date            TEXT NOT NULL,
  prompt          TEXT NOT NULL,
  my_text         TEXT NOT NULL,
  corrected_json  TEXT,
  score           DOUBLE PRECISION,
  attempts        INTEGER NOT NULL DEFAULT 0,
  last_error      TEXT,
  created_at      TEXT NOT NULL DEFAULT ${NOW}
);

CREATE TABLE IF NOT EXISTS mistakes (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date         TEXT NOT NULL,
  rule_tag     TEXT NOT NULL,
  original     TEXT NOT NULL,
  correction   TEXT NOT NULL,
  explanation  TEXT,
  source       TEXT NOT NULL DEFAULT 'writing',
  card_id      INTEGER REFERENCES cards(id) ON DELETE SET NULL,
  resolved     INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_mistakes_date ON mistakes(date);

CREATE TABLE IF NOT EXISTS missions (
  week          TEXT PRIMARY KEY,
  learner_week  INTEGER NOT NULL,
  mission_json  TEXT NOT NULL,
  status        TEXT NOT NULL DEFAULT 'active',
  reflection    TEXT,
  updated_at    TEXT
);

CREATE TABLE IF NOT EXISTS weekly_reports (
  week        TEXT PRIMARY KEY,
  json        TEXT NOT NULL,
  created_at  TEXT NOT NULL DEFAULT ${NOW}
);

CREATE TABLE IF NOT EXISTS job_runs (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind         TEXT NOT NULL,
  trigger      TEXT NOT NULL DEFAULT 'scheduler',
  started_at   TEXT NOT NULL,
  finished_at  TEXT,
  status       TEXT NOT NULL DEFAULT 'running',
  message      TEXT
);
`;
